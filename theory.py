'''Compilation: The process of converting the entire source code into machine code before execution.

Interpretation: The process of executing code line by line without creating a standalone executable.

Python Execution Model: Python first compiles source code into bytecode, then the Python Virtual Machine (PVM)
interprets the bytecode and executes it.

PVM: The Python Virtual Machine is the runtime engine that executes Python bytecode and converts it into machine-level
operations to produce the program's output.'''

'''Memory Management: Memory management is the process of allocating and deallocating memory for objects. In Python, it is
 handled automatically by the Python Memory Manager.

Garbage Collection: Garbage collection is the automatic process of reclaiming memory occupied by objects that are no longer in use.
 Python uses reference counting and a cyclic garbage collector to manage memory efficiently.'''

